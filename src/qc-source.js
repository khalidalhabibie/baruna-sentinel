/**
 * Offline adapter for a QC JSON produced by scripts/verify_igs_rinex.py.
 * In contrast to the pinned BAKO Action run, user-uploaded station metadata
 * and file provenance remain USER-DECLARED, even after GeoRinex decoding.
 */
export function parseLocalQcReport(input) {
  if (!input || input.schema !== "baruna-sentinel-real-multignss-qc-v1") {
    throw new TypeError("Expected GeoRinex QC JSON generated by the Sentinel Python script.");
  }
  const {source,sample,same_epochs_comparison:comparison,constellations_with_actual_pseudorange:systems}=input;
  if (!source || !sample || !comparison || !systems ||
    source.station_evidence !== "operator_declared_unverified" ||
    typeof source.station !== "string" ||
    !/^[A-Z0-9_-]{3,16}$/.test(source.station)) {
    throw new TypeError("Station code and explicitly unverified provenance are required.");
  }
  if (!Number.isInteger(sample.epochs) || sample.epochs < 2 ||
    typeof source.sha256_compressed !== "string" ||
    !/^[a-f0-9]{64}$/.test(source.sha256_compressed)) {
    throw new TypeError("Incomplete epochs or file checksum in GeoRinex QC report.");
  }
  const gps=comparison.gps_only_mean_satellites_with_measurements;
  const multi=comparison.multi_gnss_mean_satellites_with_measurements;
  if (!Number.isFinite(gps) || !Number.isFinite(multi) ||
      multi < gps || gps < 0 ||
      comparison.epochs_with_additional_non_gps_observations < 0 ||
      comparison.epochs_with_additional_non_gps_observations > sample.epochs) {
    throw new TypeError("Invalid pseudorange statistics.");
  }
  const observedSystems=Object.entries(systems).filter(([,x])=>
    Number.isInteger(x.pseudorange_observation_cells) && x.pseudorange_observation_cells > 0
  ).map(([name,x])=>({name,lines:x.pseudorange_observation_cells}));
  if (observedSystems.length < 2 || !observedSystems.some(x=>x.name==="GPS")) {
    throw new TypeError("A valid GPS plus additional multi-GNSS observation sample is required.");
  }
  return {
    status:"MULTI_GNSS_RECORDS_SEEN",
    version:"GeoRinex RINEX observation QC",
    marker:source.station,
    epochCount:sample.epochs,
    observedSystems,
    declaredSystems:[],
    averageGpsPseudorangeSatellitesPerEpoch:gps,
    averageAllPseudorangeSatellitesPerEpoch:multi,
    sourceUrl:source.archive_url||"USER_PROVIDED_LOCAL_FILE",
    verifiedObservationDate:String(sample.first_epoch||"unavailable").slice(0,10),
    warnings:[
      "RINEX data were locally decoded. Station identity and provenance were supplied by the operator and have not been verified by BIG.",
      "Pseudorange availability is not a geodetic positioning accuracy, subsidence rate or structural safety metric.",
      "This QC result does not validate the separate historic CSEM movement solution or port asset condition."
    ],
    linkedToCsemMovement:false,
    stationIdentityVerifiedByBig:false,
    originalFileSha256:source.sha256_compressed,
    localSourceType:"operator_declared_original_rinex"
  };
}
